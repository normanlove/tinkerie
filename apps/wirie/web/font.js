// returns array of polylines [[x,y],...] in local mm. size = cap height in mm.
// align: 'l' | 'c' | 'r', vertically centred. mirror flips horizontally (bottom layer text)
function textStrokes(str, size, align = "c", mirror = false) {
  const s = size / 6, adv = 5.6;
  const chars = [...String(str)];
  const width = Math.max(0, chars.length * adv - 1.6) * s;
  let x0 = align === "l" ? 0 : align === "r" ? -width : -width / 2;
  const out = [];
  chars.forEach((ch, i) => {
    let gl = GLYPHS[ch] || GLYPHS[ch.toUpperCase()];
    if (!gl) return;
    const lower = ch !== ch.toUpperCase();
    for (const pl of gl) {
      out.push(pl.map(([x, y]) => {
        let yy = lower ? 1.5 + y * 0.75 : y;
        let xx = x0 + (i * adv + x) * s;
        return [mirror ? -xx : xx, (yy - 3) * s];
      }));
    }
  });
  return { lines: out, width, height: size };
}
