//go:build linux

package meterie

import "testing"

func TestDescHasReportID(t *testing.T) {
	// a CP2110-style descriptor numbers its reports; a plain one doesn't
	numbered := []byte{0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x01, 0x95, 0x01, 0x75, 0x08, 0x09, 0x01, 0x81, 0x02, 0xC0}
	plain := []byte{0x06, 0xA0, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0x09, 0x02, 0x15, 0x00, 0x26, 0xFF, 0x00, 0x75, 0x08, 0x95, 0x08, 0x81, 0x02, 0xC0}
	if !descHasReportID(numbered) || descHasReportID(plain) {
		t.Fatal("report ID detection is wrong")
	}
}
